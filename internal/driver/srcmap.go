package driver

import (
	"os"
	"path/filepath"
	"strings"

	"github.com/eddyw/godart/internal/meta"
)

// srcPackage names the Dart files of 1 package that the build wrote, and the
// part file that holds the source map of the package.
type srcPackage struct {
	base  string
	mapAt string
	files []string
}

// writeSourceMaps removes the marker of each source line from the output, and
// it writes the source map of each package that the build compiled.
//
// The step runs after dart format, thus the line numbers name the lines that a
// Dart stack trace reports.
func writeSourceMaps(out, dartPkg string, pkgs []srcPackage) error {
	for _, p := range pkgs {
		data := make([]string, 0, 2*len(p.files))
		for _, path := range p.files {
			full := filepath.Join(out, path)
			text, err := os.ReadFile(full)
			if err != nil {
				return err
			}
			stripped, entries := meta.Strip(string(text))
			if stripped != string(text) {
				if err := os.WriteFile(full, []byte(stripped), 0o666); err != nil {
					return err
				}
			}
			if entries == "\n" {
				continue
			}
			data = append(data, traceKey(dartPkg, path), entries)
		}
		if err := os.WriteFile(filepath.Join(out, p.mapAt),
			[]byte(mapFile(p.base, data)), 0o666); err != nil {
			return err
		}
	}
	return nil
}

// traceKey names a Dart file the way a stack trace of the Dart VM names it.
func traceKey(dartPkg, path string) string {
	slash := filepath.ToSlash(path)
	if rest, ok := strings.CutPrefix(slash, "lib/"); ok {
		return "package:" + dartPkg + "/" + rest
	}
	return slash
}

func mapFile(base string, data []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by gart. DO NOT EDIT.\n\n")
	b.WriteString("part of '" + base + ".dart';\n\n")
	// dart format writes an empty list on 1 line. The map file passes no
	// format run, thus the writer gives it the form of dart format.
	if len(data) == 0 {
		b.WriteString("const $srcmapData = <String>[];\n")
		return b.String()
	}
	b.WriteString("const $srcmapData = <String>[\n")
	for _, item := range data {
		b.WriteString("  '" + dartQuote(item) + "',\n")
	}
	b.WriteString("];\n")
	return b.String()
}

// dartQuote escapes the 3 characters that end a Dart string or start an
// interpolation inside one.
func dartQuote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `'`, `\'`, `$`, `\$`, "\n", `\n`)
	return r.Replace(s)
}
