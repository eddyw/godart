func (e *emitter) expr(x ir.Expr) string {
	switch x := x.(type) {
	case nil:
		return ""
	case *ir.Const:
		return e.constant(x.Value, x.Type)
	case *ir.Ident:
		text := e.identExpr(x)
		if fn, ok := x.Obj.(*types.Func); ok {
			return e.functionValue(fn, text)
		}
		return text
	case *ir.Blank:
		return "_"
	case *ir.Zero:
		return e.zero(x.Type)
	case *ir.Field:
		e.mark(x.Pos)
		text := e.deref(x.X) + "." + e.fieldDartName(x.X.GoType(), x.Name)
		if e.fieldStorageType(x.GoType()) != e.dartType(x.GoType()) {
			return "(" + text + " as " + e.dartType(x.GoType()) + ")"
		}
		return text
	case *ir.Index:
		return e.index(x)
	case *ir.TypeAssert:
		return e.typeAssert(x)
	case *ir.TypeTest:
		return e.typeTest(x.X, x.Assert)
	case *ir.MapRead:
		return fmt.Sprintf("%s.get2(%s)", e.container(x.X), e.expr(x.Key))
	case *ir.Slice:
		return e.sliceExpr(x)
	case *ir.Call:
		return e.call(x)
	case *ir.MethodExpr:
		return e.methodExpr(x)
	case *ir.FuncInst:
		return e.funcInst(x)
	case *ir.Method:
		return e.methodValue(x)
	case *ir.Builtin:
		return e.builtin(x)
	case *ir.Binary:
		return e.binary(x)
	case *ir.Unary:
		return e.unary(x)
	case *ir.Conv:
		return e.conv(x)
	case *ir.Composite:
		return e.composite(x)
	case *ir.FuncLit:
		return e.funcLit(x)
	case *ir.Copy:
		return e.copyExpr(x)
	case *ir.Recv:
		if x.Comma {
			return fmt.Sprintf("%s.receive()", e.chanExpr(x.Chan))
		}
		return fmt.Sprintf("%s.receive().$1", e.chanExpr(x.Chan))
	case *ir.RecordField:
		return fmt.Sprintf("%s.$%d", e.expr(x.X), x.Index+1)
	case *ir.SelectList:
		return e.selectList(x)
	case *ir.SelectRun:
		return fmt.Sprintf("$gi($select(%s, %t))", e.expr(x.List), x.HasDefault)
	case *ir.Record:
		parts := make([]string, len(x.Elems))
		for i, el := range x.Elems {
			parts[i] = e.expr(el)
		}
		return "(" + strings.Join(parts, ", ") + ")"
	}
	e.fail("the expression %T has no Dart form", x)
	return "null"
}

func (e *emitter) functionValue(fn *types.Func, text string) string {
	if e.cfg.Fset == nil || !fn.Pos().IsValid() {
		return text
	}
	pkg := fn.Pkg()
	path := pkg.Path()
	if pkg.Name() == "main" {
		path = "main"
	}
	info := fmt.Sprintf("%s.%s|%s|%d", path, fn.Name(), e.goFileInPackage(fn.Pos(), pkg), e.cfg.Fset.Position(fn.Pos()).Line)
	return fmt.Sprintf("$functionValue(%s, %s)", text, e.stringLit(info))
}

func (e *emitter) methodFunctionValue(recv types.Type, fn *types.Func, text string) string {
	base := recv
	if p, ok := types.Unalias(base).(*types.Pointer); ok {
		base = p.Elem()
	}
	named, ok := types.Unalias(base).(*types.Named)
	if !ok || named.TypeParams().Len() > 0 || named.TypeArgs().Len() > 0 {
		return text
	}
	obj := named.Obj()
	pkg := obj.Pkg()
	path := "go:builtin"
	if pkg != nil {
		path = pkg.Path()
		if pkg.Name() == "main" {
			path = "main"
		}
	}
	name := obj.Name()
	if isPointerType(recv) {
		name = "(*" + name + ")"
	}
	file, line := "<autogenerated>", 1
	sig := fn.Type().(*types.Signature)
	if sig.Recv() != nil && types.Identical(recv, sig.Recv().Type()) && e.cfg.Fset != nil && fn.Pos().IsValid() {
		file, line = e.goFileInPackage(fn.Pos(), fn.Pkg()), e.cfg.Fset.Position(fn.Pos()).Line
	}
	info := fmt.Sprintf("%s.%s.%s|%s|%d", path, name, fn.Name(), file, line)
	return fmt.Sprintf("$functionValue(%s, %s)", text, e.stringLit(info))
}

func (e *emitter) identExpr(x *ir.Ident) string {
	if x.Boxed {
		return e.identName(x) + ".v"
	}
	return e.identName(x)
}

// identName gives the Dart name of an identifier. A package level name takes
// its prefix and its suffix, and a copy of a box takes the name of the copy.
func (e *emitter) identName(x *ir.Ident) string {
	if to := e.renames[x.Name]; to != "" {
		return to
	}
	if x.Obj == nil {
		return x.Name
	}
	if x.Obj.Pkg() != nil && x.Obj.Parent() == x.Obj.Pkg().Scope() {
		return e.qualify(x.Obj, e.topName(x.Obj.Pkg(), x.Obj.Name()))
	}
	return x.Name
}

// deref reads through a pointer. Go panics with the nil dereference error
// when the pointer is nil, and the bare null check of Dart gives an error of
// Dart. An operand with an effect takes a parameter of its own, thus the read
// runs the effect 1 time.
//
// The guard holds a location. Dart takes a field write on the result of an
// expression, thus a write through the pointer reads the same guard.
func (e *emitter) deref(x ir.Expr) string {
	text := e.expr(x)
	p, ok := typeset.Core(x.GoType()).(*types.Pointer)
	if !ok {
		return text
	}
	if tp, ok := types.Unalias(p.Elem()).(*types.TypeParam); ok {
		return fmt.Sprintf("$deref<%s>(%s)", e.dartType(tp), text)
	}
	form := e.dartType(p)
	simple := exprIsSimple(x)
	if named, ok := types.Unalias(p.Elem()).(*types.Named); ok && recursiveLocalStruct(named) {
		form = e.dartType(p.Elem()) + "?"
		text = "(" + text + " as " + form + ")"
		simple = false
	}
	if form == "Object?" && needsBox(p.Elem()) {
		// A pointer to a type that names itself erases to Object?, thus the
		// read needs the real cell type back.
		form = "$Ptr<" + e.dartType(p.Elem()) + ">?"
		text = "(" + text + " as " + form + ")"
		simple = false
	}
	var guard string
	if simple {
		guard = "(" + text + " == null ? $panicNil() : " + text + "!)"
	} else {
		guard = fmt.Sprintf("((%s $p) => ($p == null ? $panicNil() : $p!))(%s)",
			form, text)
	}
	if needsBox(p.Elem()) {
		return guard + ".v"
	}
	return guard
}

// exprIsSimple reports whether the expression holds no call, so its text can
// stand 2 times in a wrapper.
func exprIsSimple(x ir.Expr) bool {
	switch x := x.(type) {
	case *ir.Ident:
		return true
	case *ir.Const:
		return true
	case *ir.Zero:
		return true
	case *ir.Blank:
		return true
	case *ir.FuncLit:
		return x != nil
	}
	return false
}

func (e *emitter) constant(v constant.Value, t types.Type) string {
	if text, ok := e.mixedConst(v, t); ok {
		return text
	}
	switch {
	case isString(t):
		return e.stringLit(constant.StringVal(v))
	case isFloat(t):
		f, _ := constant.Float64Val(constant.ToFloat(v))
		if basicOf(t).Kind() == types.Float32 {
			return "$f32(" + floatConst(f) + ")"
		}
		return float64Const(f)
	case isComplexType(t):
		return complexConst(v, t)
	case isInteger(t):
		return intConst(v, t)
	}
	if v.Kind() == constant.Bool {
		return strconv.FormatBool(constant.BoolVal(v))
	}
	e.fail("the constant %s has no Dart form", v)
	return "null"
}

// A type argument selects the constant representation and precision.
func (e *emitter) mixedConst(v constant.Value, t types.Type) (string, bool) {
	tp, ok := types.Unalias(t).(*types.TypeParam)
	if !ok {
		return "", false
	}
	set, ok := typeset.Describe(tp)
	if !ok || !set.Numeric || set.Integer {
		return "", false
	}
	d := e.dictOf(tp)
	terms, _ := typeset.Terms(tp.Constraint())
	forms := map[types.BasicInfo]bool{}
	for _, term := range terms {
		b := types.Unalias(term).Underlying().(*types.Basic)
		forms[b.Info()&(types.IsInteger|types.IsFloat|types.IsComplex)] = true
	}
	var values, kinds []string
	for _, term := range terms {
		if basicOf(term).Kind() == types.Float32 {
			f, _ := constant.Float64Val(constant.ToFloat(v))
			values = append(values, "$f32("+floatConst(f)+")")
			kinds = append(kinds, "GoFloat32")
			break
		}
	}
	if forms[types.IsInteger] {
		values = append(values, intConst(v, types.Typ[types.Int]))
		kinds = append(kinds, "GoInt")
	}
	if forms[types.IsFloat] {
		f, _ := constant.Float64Val(constant.ToFloat(v))
		values = append(values, float64Const(f))
		kinds = append(kinds, "GoFloat64")
	}
	if forms[types.IsComplex] {
		values = append(values, complexConst(v, types.Typ[types.Complex128]))
		kinds = append(kinds, "GoComplex")
	}
	text := values[len(values)-1]
	for i := len(values) - 2; i >= 0; i-- {
		text = fmt.Sprintf("(%s.zero() is %s ? %s : %s)", d, kinds[i], values[i], text)
	}
	return e.narrow(tp, text), true
}

// complexConst writes a complex constant. A constant of complex64 rounds each
// part to 32 bits, exactly as the go compiler does.
func complexConst(v constant.Value, t types.Type) string {
	c := constant.ToComplex(v)
	re, _ := constant.Float64Val(constant.Real(c))
	im, _ := constant.Float64Val(constant.Imag(c))
	if b := basicOf(t); b != nil && b.Kind() == types.Complex64 {
		re = float64(float32(re))
		im = float64(float32(im))
		return fmt.Sprintf("GoComplex32($f32(%s), $f32(%s))", floatConst(re), floatConst(im))
	}
	return fmt.Sprintf("GoComplex(%s, %s)", floatConst(re), floatConst(im))
}

// intConst writes a Go integer constant. A JS number holds 53 bits of an
// integer, thus a value outside that range takes the form of 2 32-bit
// halves, and each other value takes the plain form.
func intConst(v constant.Value, t types.Type) string {
	i := constant.ToInt(v)
	n, ok := constant.Int64Val(i)
	if !ok {
		// A value above the range of int64 keeps its 64 bit pattern. Dart
		// reads the pattern as a negative number, and the unsigned helpers
		// give the Go result.
		u, _ := constant.Uint64Val(i)
		n = int64(u)
	}
	if n > -(1<<53) && n < 1<<53 {
		return "$gi(" + strconv.FormatInt(n, 10) + ")"
	}
	return fmt.Sprintf("$gi2(%d, %d)", int32(n>>32), int64(uint32(n)))
}

func float64Const(f float64) string {
	bits := math.Float64bits(f)
	return fmt.Sprintf("const GoFloat64.fromBits(%d, %d)", uint32(bits>>32), uint32(bits))
}

func floatConst(f float64) string {
	switch {
	case math.IsInf(f, 1):
		return "double.infinity"
	case math.IsInf(f, -1):
		return "double.negativeInfinity"
	case math.IsNaN(f):
		return "double.nan"
	}
	text := strconv.FormatFloat(f, 'g', -1, 64)
	if !strings.ContainsAny(text, ".eE") {
		text += ".0"
	}
	if f < 0 {
		return "(" + text + ")"
	}
	return text
}

// stringConst writes a Go string constant. The bytes go into the output when
// the text is not valid UTF-8, because a Dart string cannot hold such bytes.
func stringConst(s string) string {
	if !isPrintableUTF8(s) {
		parts := make([]string, len(s))
		for i := 0; i < len(s); i++ {
			parts[i] = strconv.Itoa(int(s[i]))
		}
		return "GoString.fromBytes(<int>[" + strings.Join(parts, ", ") + "])"
	}
	var b strings.Builder
	b.WriteString("GoString.fromString('")
	for _, r := range s {
		switch r {
		case '\'':
			b.WriteString(`\'`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case '$':
			b.WriteString(`\$`)
		default:
			if r < 0x20 || r == 0x7F {
				fmt.Fprintf(&b, `\u{%x}`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteString("')")
	return b.String()
}

func isPrintableUTF8(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] >= 0x80 {
			return validUTF8(s)
		}
	}
	return true
}

func validUTF8(s string) bool {
	for _, r := range s {
		if r == 0xFFFD {
			return false
		}
	}
	return true
}

// unsignedBound selects the decimal form of a 64-bit bound in a panic.
// Narrower unsigned values fit in a signed Dart int.
func (e *emitter) unsignedBound(x ir.Expr) string {
	if x == nil {
		return "false"
	}
	if isUnsigned64(x.GoType()) {
		return "true"
	}
	if set, ok := typeset.Describe(x.GoType()); ok && set.MixedSign() {
		return e.dictOf(x.GoType()) + ".unsigned64"
	}
	return "false"
}

func (e *emitter) unsArg(x ir.Expr) string {
	if flag := e.unsignedBound(x); flag != "false" {
		return ", " + flag
	}
	return ""
}

// rangeTail gives the optional arguments of Slice.range. three names a slice
// expression of 3 bounds, and byLen names a report that writes "with length".
// The flag of each bound follows them, and each 1 stands only when a bound
// holds an unsigned type.
func (e *emitter) rangeTail(three, byLen bool, low, high, max ir.Expr) string {
	l, h, m := e.unsignedBound(low), e.unsignedBound(high), e.unsignedBound(max)
	if l == "false" && h == "false" && m == "false" {
		if !three && !byLen {
			return ""
		}
		return fmt.Sprintf(", %v, %v", three, byLen)
	}
	return fmt.Sprintf(", %v, %v, %v, %v, %v", three, byLen, l, h, m)
}

func (e *emitter) index(x *ir.Index) string {
	e.mark(x.Pos)
	if text := e.deepIndex(x); text != "" {
		return text
	}
	container := x.X.GoType()
	if typeset.Core(container) == nil && typeset.ArrayOrSlice(container) {
		return fmt.Sprintf("$sequenceIndex<%s>(%s, %s%s)", e.dartType(x.Type), e.expr(x.X), e.expr(x.Index), e.unsArg(x.Index))
	}
	if typeset.Core(container) == nil && typeset.BytesOrText(container) {
		return fmt.Sprintf("%s.at!(%s, %s%s)",
			e.dictOf(container), e.expr(x.X), e.expr(x.Index), e.unsArg(x.Index))
	}
	if isMapType(container) {
		return fmt.Sprintf("%s.get(%s)", e.container(x.X), e.expr(x.Index))
	}
	uns := e.unsArg(x.Index)
	if isString(container) {
		return fmt.Sprintf("%s.$at(%s%s)", e.expr(x.X), e.expr(x.Index), uns)
	}
	// The type argument stands in the text. Dart reads the context of the
	// expression for it, and an operand of `-` gives `num`.
	if isPointerType(container) {
		return fmt.Sprintf("$arrayIndex<%s>(%s, %s%s)",
			e.dartType(x.Type), e.deref(x.X), e.expr(x.Index), uns)
	}
	if isArrayType(container) {
		return fmt.Sprintf("$arrayIndex<%s>(%s, %s%s)",
			e.dartType(x.Type), e.expr(x.X), e.expr(x.Index), uns)
	}
	if uns != "" {
		return fmt.Sprintf("%s.$at(%s%s)", e.container(x.X), e.expr(x.Index), uns)
	}
	return fmt.Sprintf("%s.$at(%s)", e.container(x.X), e.expr(x.Index))
}

// container gives the Dart text of the container of an index expression, with
// a cast when the Dart form of its type is the top type of Dart.
//
// A type that names itself through a slice or a map holds no finite Dart form,
// thus each use of it takes Object?. Dart reads no index operator and no set
// method on that type, and the cast names the form of the underlying type.
func (e *emitter) container(x ir.Expr) string {
	text := e.expr(x)
	t := x.GoType()
	if t == nil || e.dartType(t) != erasedDartType {
		return text
	}
	under := types.Unalias(t).Underlying()
	switch under.(type) {
	case *types.Map, *types.Slice:
	default:
		return text
	}
	form := e.dartType(under)
	if form == erasedDartType {
		return text
	}
	return fmt.Sprintf("(%s as %s)", text, form)
}

// erasedDartType is the Dart form of a Go type that holds no finite one.
const erasedDartType = "Object?"

// indexTarget gives the start and the end of a write into an array. head is
// empty when the write uses the index operator of Dart.
func (e *emitter) indexTarget(x *ir.Index) (head, tail string) {
	e.mark(x.Pos)
	container := x.X.GoType()
	uns := e.unsArg(x.Index)
	if typeset.Core(container) == nil && typeset.ArrayOrSlice(container) {
		return fmt.Sprintf("$sequenceSet<%s>(%s, %s", e.dartType(x.Type), e.expr(x.X), e.expr(x.Index)), uns
	}
	if isPointerType(container) {
		return fmt.Sprintf("$arraySet<%s>(%s, %s",
			e.dartType(x.Type), e.deref(x.X), e.expr(x.Index)), uns
	}
	if isArrayType(container) {
		return fmt.Sprintf("$arraySet<%s>(%s, %s",
			e.dartType(x.Type), e.expr(x.X), e.expr(x.Index)), uns
	}
	if isSliceType(container) {
		return fmt.Sprintf("%s.$set(%s", e.container(x.X), e.expr(x.Index)), uns
	}
	return "", ""
}

func (e *emitter) assignArray(dst string, t types.Type, value string) string {
	a, _ := types.Unalias(t).Underlying().(*types.Array)
	if a != nil && needsElementCopy(a.Elem()) {
		return fmt.Sprintf("$assignArray(%s, %s, (a, b) => %s)", dst, value, e.assignElem("a", "b", a.Elem()))
	}
	return fmt.Sprintf("$assignArray(%s, %s)", dst, value)
}

func (e *emitter) sliceExpr(x *ir.Slice) string {
	e.mark(x.Pos)
	low := "$gi(0)"
	if x.Low != nil {
		low = e.expr(x.Low)
	}
	source := x.X.GoType()
	if typeset.BytesOrText(source) {
		high := fmt.Sprintf("%s.length!(%s)", e.dictOf(source), e.expr(x.X))
		if x.High != nil {
			high = e.expr(x.High)
		}
		return fmt.Sprintf("%s.slice!(%s, %s, %s, %s, %s)",
			e.dictOf(source), e.expr(x.X), lowOrZero(x.Low, e), high, e.unsignedBound(x.Low), e.unsignedBound(x.High))
	}
	if isString(source) {
		high := fmt.Sprintf("$gi(%s.length)", e.expr(x.X))
		if x.High != nil {
			high = e.expr(x.High)
		}
		tail := ""
		if e.unsignedBound(x.Low) != "false" || e.unsignedBound(x.High) != "false" {
			tail = fmt.Sprintf(", %s, %s", e.unsignedBound(x.Low), e.unsignedBound(x.High))
		}
		return fmt.Sprintf("$substring(%s, %s, %s%s)",
			e.expr(x.X), low, high, tail)
	}
	if isArrayType(source) || isPointerType(source) {
		text := e.expr(x.X)
		if isPointerType(source) {
			text = e.deref(x.X)
		}
		high := fmt.Sprintf("$arrayLength(%s)", text)
		if x.High != nil {
			high = e.expr(x.High)
		}
		max := fmt.Sprintf("$arrayLength(%s)", text)
		if x.Max != nil {
			max = e.expr(x.Max)
		}
		// An array and a pointer to an array each report "with length" in a
		// bound panic, and a slice reports "with capacity".
		return fmt.Sprintf("Slice.of(%s).range(%s, %s, %s%s)",
			text, low, high, max,
			e.rangeTail(x.Max != nil, true, x.Low, x.High, x.Max))
	}
	x0 := e.sliceText(x.X)
	high := fmt.Sprintf("%s.$length", x0)
	if x.High != nil {
		high = e.expr(x.High)
	}
	max := fmt.Sprintf("%s.$capacity", x0)
	if x.Max != nil {
		max = e.expr(x.Max)
	}
	return fmt.Sprintf("%s.range(%s, %s, %s%s)", x0, low, high, max,
		e.rangeTail(x.Max != nil, false, x.Low, x.High, x.Max))
}

func (e *emitter) copyExpr(x *ir.Copy) string {
	if tp, ok := types.Unalias(x.Type).(*types.TypeParam); ok {
		return fmt.Sprintf("%s.copyOf(%s)", e.dictOf(tp), e.expr(x.X))
	}
	if isArrayType(x.Type) {
		return e.copyArray(e.expr(x.X), x.Type)
	}
	return e.deref(x.X) + ".$copy()"
}

func (e *emitter) funcLit(x *ir.FuncLit) string {
	var b strings.Builder
	fmt.Fprintf(&b, "(%s) {\n", e.params(x.Params))
	e.buf.WriteString("")
	// The inner emitter shares each package wide map. A class of an unnamed
	// struct type and the name of a shadowed function must reach the library
	// file of the package.
	inner := &emitter{pkg: e.pkg, prefixes: e.prefixes, base: e.base,
		dictReads:    e.dictReads,
		merges:       e.merges,
		instByStruct: e.instByStruct,
		methods:      e.methods, inClass: e.inClass, initNames: e.initNames,
		breakables: e.breakables, labelSeq: e.labelSeq,
		anon: e.anon, shadowed: e.shadowed,
		nilChans: e.nilChans, instDescs: e.instDescs, descTexts: e.descTexts,
		inlineDescTypes: e.inlineDescTypes,
		cfg:             e.cfg, nilPrefix: e.nilPrefix,
		typeParams: e.typeParams,
		funcIds:    e.funcIds, funcByObj: e.funcByObj, varLitId: e.varLitId,
		lits:    e.lits,
		renames: e.withRenames(e.captureRenames(x.Captured))}
	inner.curGoName = e.literalName(x)
	inner.inLiteral = !x.Range
	inner.funcFile = e.funcFile
	if e.cfg.Fset != nil {
		inner.funcFile = e.goFile(x.Pos)
		inner.funcLine = e.cfg.Fset.Position(x.Pos).Line
	}
	inner.goMarkFile = inner.funcFile
	inner.line("%s%s|%s|%d", fileMark, inner.funcFile, inner.curGoName, inner.funcLine)
	inner.curFuncId = e.funcId(x)
	inner.boxParams(x.Params)
	if x.Machine != nil {
		inner.machineBody(&ir.Func{Params: x.Params, Results: x.Results, Body: x.Body, Machine: x.Machine, End: x.End}, "")
	} else {
		inner.emitBody(x.Results, x.Defers, x.Body, x.End)
	}
	inner.line("%s%s|%s|%d", fileMark, e.funcFile, e.curGoName, e.funcLine)
	e.errs = append(e.errs, inner.errs...)
	e.labelSeq = inner.labelSeq
	e.dictReads = inner.dictReads
	e.frames = append(e.frames, inner.frames...)
	// The 2 emitters share the map of the prefixes and hold a list of the
	// added imports of their own. An import that the body of the literal
	// added must reach the library file, thus the outer list takes it.
	e.extra = append(e.extra, inner.extra...)
	b.WriteString(inner.buf.String())
	b.WriteString("}")
	if e.cfg.Fset == nil || !x.Pos.IsValid() {
		return b.String()
	}
	info := fmt.Sprintf("%s|%s|%d", inner.curGoName, inner.funcFile, inner.funcLine)
	return fmt.Sprintf("$functionValue(%s, %s)", b.String(), e.stringLit(info))
}

func (e *emitter) literalName(literal *ir.FuncLit) string {
	if literal.Range {
		return fmt.Sprintf("%s-range%d", e.curGoName, literal.Ordinal)
	}
	if e.inLiteral {
		return fmt.Sprintf("%s.%d", e.curGoName, literal.Ordinal)
	}
	return fmt.Sprintf("%s.func%d", e.curGoName, literal.Ordinal)
}

// equal writes the Go comparison `a == b` for 2 values of the same type.
func (e *emitter) equal(a, b ir.Expr) string {
	if text, ok := e.nilTest(a, b); ok {
		return text
	}
	if text, ok := e.nilTest(b, a); ok {
		return text
	}
	if isDartObjectPointer(a.GoType()) {
		return fmt.Sprintf("identical(%s, %s)", e.expr(a), e.expr(b))
	}
	if ai, bi := isInterfaceType(a.GoType()), isInterfaceType(b.GoType()); ai != bi {
		if ai {
			return fmt.Sprintf("%s == %s", e.expr(a), e.box(b, b.GoType()))
		}
		return fmt.Sprintf("%s == %s", e.box(a, a.GoType()), e.expr(b))
	}
	if tp, ok := types.Unalias(a.GoType()).(*types.TypeParam); ok {
		return fmt.Sprintf("%s.equal(%s, %s)", e.dictOf(tp), e.expr(a), e.expr(b))
	}
	if isArrayType(a.GoType()) {
		return fmt.Sprintf("$goEqual(%s, %s, %s)", e.expr(a), e.expr(b), e.descriptorOf(a.GoType()))
	}
	// A pointer to a struct is the Dart object of the struct, and the class
	// compares the fields, thus 2 allocations with equal fields would compare
	// equal. The comparison reads the identity. Each other pointer holds a
	// cell, and the cell compares its location.
	if _, ok := typeset.Core(a.GoType()).(*types.Pointer); ok {
		return fmt.Sprintf("$goEqual(%s, %s, %s)", e.expr(a), e.expr(b), e.descriptorOf(a.GoType()))
	}
	return fmt.Sprintf("%s == %s", e.expr(a), e.expr(b))
}

// nilTest writes the comparison of a value with nil. A slice and a map hold the
// nil state in a field, because the zero value is an object and not null.
func (e *emitter) nilTest(x, other ir.Expr) (string, bool) {
	if _, ok := other.(*ir.Zero); !ok {
		return "", false
	}
	switch typeset.Core(x.GoType()).(type) {
	case *types.Slice, *types.Map, *types.Chan:
		// A slice, a map, and a channel each hold the zero value as an object.
		// The Dart type of a type that names itself erases to Object?, and
		// the test needs the container type back.
		text := e.expr(x)
		if e.dartType(x.GoType()) == "Object?" {
			return "(" + text + " as dynamic).isNil as bool", true
		}
		return text + ".isNil", true
	case *types.Pointer, *types.Signature, *types.Interface:
		return e.expr(x) + " == null", true
	}
	return "", false
}

func (e *emitter) binary(x *ir.Binary) string {
	left, right := e.expr(x.X), e.expr(x.Y)
	t := x.X.GoType()
	if tp, ok := types.Unalias(t).(*types.TypeParam); ok {
		if set, ok := typeset.Describe(tp); ok && set.Numeric && (set.MixedSign() || (!set.Integer && !set.Float) || (set.Float && e.mixedForm(tp))) {
			method := map[token.Token]string{token.QUO: "quotient", token.REM: "remainder", token.SHR: "shiftRight"}[x.Op]
			if method != "" {
				if x.Op == token.SHR {
					right = e.shiftCount(x.Y)
				}
				return fmt.Sprintf("%s.%s(%s, %s)", e.dictOf(tp), method, left, right)
			}
		}
	}
	switch x.Op {
	case token.LAND:
		return e.narrow(x.Type, fmt.Sprintf("(%s && %s)", left, right))
	case token.LOR:
		return e.narrow(x.Type, fmt.Sprintf("(%s || %s)", left, right))
	case token.EQL, token.NEQ:
		text := e.equal(x.X, x.Y)
		if x.Op == token.NEQ {
			return e.narrow(x.Type, "(!("+text+"))")
		}
		return e.narrow(x.Type, "("+text+")")
	case token.LSS, token.LEQ, token.GTR, token.GEQ:
		return e.narrow(x.Type, e.compare(x.Op, x.X, x.Y))
	case token.QUO:
		if isInteger(t) {
			if isUnsigned64(t) {
				return fmt.Sprintf("$udiv(%s, %s)", left, right)
			}
			return e.narrow(t, fmt.Sprintf("$div(%s, %s)", left, right))
		}
		return e.narrow(t, fmt.Sprintf("(%s / %s)", left, right))
	case token.REM:
		if isUnsigned64(t) {
			return fmt.Sprintf("$umod(%s, %s)", left, right)
		}
		return e.narrow(t, fmt.Sprintf("$mod(%s, %s)", left, right))
	case token.SHL:
		return e.narrow(t, fmt.Sprintf("$shl(%s, %s)", left, e.shiftCount(x.Y)))
	case token.SHR:
		if isUnsigned(t) {
			return e.narrow(t, fmt.Sprintf("$ushr(%s, %s)", left, e.shiftCount(x.Y)))
		}
		return e.narrow(t, fmt.Sprintf("$shr(%s, %s)", left, e.shiftCount(x.Y)))
	case token.AND_NOT:
		return e.narrow(t, fmt.Sprintf("(%s & ~%s)", left, right))
	case token.ADD:
		if isString(t) {
			return e.narrow(x.Type, fmt.Sprintf("$concat(%s, %s)", left, right))
		}
		if set, ok := typeset.Describe(t); ok && set.Addable && !set.Numeric {
			return fmt.Sprintf("%s.add(%s, %s)", e.dictOf(t), left, right)
		}
	}
	if tp, ok := types.Unalias(t).(*types.TypeParam); ok && e.mixedForm(tp) {
		left = "(" + left + " as dynamic)"
	}
	return e.narrow(t, fmt.Sprintf("(%s %s %s)", left, x.Op.String(), right))
}

// shiftCount writes the right operand of a shift. An untyped constant count
// can hold the float kind or the complex kind, and the operation needs the
// int form of its value. A constant count of 64 or more takes the text 64: a
// Dart int holds 64 bits, thus the 2 counts give 1 result, and the unsigned
// form of a large count would read as a negative int.
func (e *emitter) shiftCount(y ir.Expr) string {
	c, ok := y.(*ir.Const)
	if !ok {
		text := e.expr(y)
		// A count of a 64 bit unsigned type is never negative in Go. Such a
		// count above the largest int64 reads as a negative number in Dart,
		// thus the helper saturates it at the width of the value.
		if isUnsigned64(y.GoType()) {
			return "$ucount(" + text + ")"
		}
		return text
	}
	i := constant.ToInt(c.Value)
	if constant.Compare(i, token.GEQ, constant.MakeInt64(64)) {
		return "$gi(64)"
	}
	if isFloat(c.Type) || isComplexType(c.Type) {
		return intConst(c.Value, types.Typ[types.Int])
	}
	return e.expr(y)
}

// compare writes an ordered comparison. A string compares by byte, and a 64 bit
// unsigned value needs the unsigned helper.
func (e *emitter) compare(op token.Token, a, b ir.Expr) string {
	left, right := e.expr(a), e.expr(b)
	if tp, ok := types.Unalias(a.GoType()).(*types.TypeParam); ok {
		set, described := typeset.Describe(tp)
		if e.mixedForm(tp) || (described && set.MixedSign()) {
			if op == token.GTR || op == token.GEQ {
				left, right = right, left
			}
			method := "less"
			if op == token.LEQ || op == token.GEQ {
				method = "lessEqual"
			}
			return fmt.Sprintf("%s.%s(%s, %s)", e.dictOf(tp), method, left, right)
		}
	}
	if isString(a.GoType()) {
		return fmt.Sprintf("($compare(%s, %s) %s 0)", left, right, op.String())
	}
	if isUnsigned64(a.GoType()) {
		switch op {
		case token.LSS:
			return fmt.Sprintf("$ult(%s, %s)", left, right)
		case token.LEQ:
			return fmt.Sprintf("$ule(%s, %s)", left, right)
		case token.GTR:
			return fmt.Sprintf("$ult(%s, %s)", right, left)
		case token.GEQ:
			return fmt.Sprintf("$ule(%s, %s)", right, left)
		}
	}
	return fmt.Sprintf("(%s %s %s)", left, op.String(), right)
}

// narrow keeps the value of a narrow type inside its range. A Dart int holds 64
// bits, thus a smaller Go type needs a mask after each operation.
//
// A type parameter needs a cast. Go gives the operation the type of the
// parameter, and Dart gives it the bound of the parameter.
func (e *emitter) narrow(t types.Type, text string) string {
	if tp, ok := types.Unalias(t).(*types.TypeParam); ok {
		if core, ok := typeset.Core(tp).(*types.Basic); ok && core.Info()&types.IsBoolean != 0 {
			return fmt.Sprintf("(%s as %s)", text, e.dartType(tp))
		}
	}
	if m := mask(t); m != "" {
		return m + "(" + text + ")"
	}
	if tp, ok := types.Unalias(t).(*types.TypeParam); ok {
		// Apply concrete precision after arithmetic, including complex components.
		if set, ok := typeset.Describe(tp); ok && set.Numeric {
			if !e.mixedForm(tp) {
				return e.dictOf(tp) + ".mask(" + text + ")"
			}
			return e.dictOf(tp) + ".mask(" + text + " as " + e.typeParamName(tp) + ")"
		}
		return "(" + text + " as " + e.typeParamName(tp) + ")"
	}
	return text
}

func (e *emitter) unary(x *ir.Unary) string {
	switch x.Op {
	case token.AND:
		if ptr, ok := x.X.(*ir.Unary); ok && ptr.Op == token.MUL {
			return fmt.Sprintf("((%s $p) => $p == null ? $panicNil() : $p)(%s)", e.dartType(ptr.X.GoType()), e.expr(ptr.X))
		}
		// A box is the address of the variable that holds it. The read of a
		// boxed variable adds the field, thus the address drops it.
		if id, ok := x.X.(*ir.Ident); ok && id.Boxed {
			return e.identName(id)
		}
		if p, ok := typeset.Core(x.Type).(*types.Pointer); ok && needsBox(p.Elem()) {
			return e.addressOf(x.X, p.Elem())
		}
		return e.expr(x.X)
	case token.MUL:
		return e.deref(x.X)
	case token.SUB:
		if tp, ok := types.Unalias(x.Type).(*types.TypeParam); ok && e.mixedForm(tp) {
			return e.narrow(x.Type, "(-("+e.expr(x.X)+" as dynamic))")
		}
		return e.narrow(x.Type, "(-"+e.expr(x.X)+")")
	case token.NOT:
		return e.narrow(x.Type, "(!"+e.expr(x.X)+")")
	case token.XOR:
		return e.narrow(x.Type, "(~"+e.expr(x.X)+")")
	case token.ADD:
		return e.expr(x.X)
	}
	e.fail("the operator %s has no Dart form", x.Op)
	return "null"
}

// addressExpr writes the address of a value that needs a cell. A boxed variable
// gives its box, and each other form gives a cell of its own.
func (e *emitter) addressExpr(x ir.Expr) string {
	if id, ok := x.(*ir.Ident); ok && id.Boxed {
		return e.identName(id)
	}
	return e.addressOf(x, x.GoType())
}

// addressOf writes a pointer to a field of a struct, or to an element of a
// slice or an array. Such a location holds a Dart value, thus the pointer holds
// the object and the index of the location.
func (e *emitter) addressOf(x ir.Expr, elem types.Type) string {
	switch x := x.(type) {
	case *ir.Unary:
		if x.Op == token.MUL {
			return fmt.Sprintf("((%s $p) => $p == null ? $panicNil() : $p)(%s)", e.dartType(x.X.GoType()), e.expr(x.X))
		}
	case *ir.Ident:
		if obj, ok := x.Obj.(*types.Var); ok && obj.Exported() && obj.Parent() == obj.Pkg().Scope() {
			owner := dartText(obj.Pkg().Path() + "." + obj.Name())
			variable := e.identName(x)
			return fmt.Sprintf("$Ref<String, %s>('%s', 0, ($r, $i) => %s, ($r, $i, $v) => %s = $v)",
				e.dartType(elem), owner, variable, variable)
		}
	case *ir.Field:
		owner := x.X.GoType()
		if p, ok := typeset.Core(owner).(*types.Pointer); ok {
			owner = p.Elem()
		}
		field := e.fieldDartName(x.X.GoType(), x.Name)
		read := "$r." + field
		if e.fieldStorageType(elem) != e.dartType(elem) {
			read = "(" + read + " as " + e.dartType(elem) + ")"
		}
		return fmt.Sprintf("$Ref<%s, %s>(%s, %d, ($r, $i) => %s, ($r, $i, $v) => $r.%s = $v)",
			e.dartType(owner), e.dartType(elem), e.deref(x.X), fieldIndex(owner, x.Name),
			read, field)
	case *ir.Composite:
		// A composite literal holds no name, thus its address takes a box of
		// its own. Each read of that pointer reaches the same value.
		return fmt.Sprintf("Box<%s>(%s)", e.dartType(elem), e.expr(x))
	case *ir.Index:
		container := x.X.GoType()
		if typeset.Core(container) == nil && typeset.ArrayOrSlice(container) {
			return fmt.Sprintf("$sequencePtr<%s>(%s, %s%s)", e.dartType(elem), e.expr(x.X), e.expr(x.Index), e.unsArg(x.Index))
		}
		if isPointerType(container) {
			return fmt.Sprintf("$indexPtr(%s, %s%s)", e.deref(x.X), e.expr(x.Index), e.unsArg(x.Index))
		}
		if isArrayType(container) {
			return fmt.Sprintf("$indexPtr(%s, %s%s)", e.expr(x.X), e.expr(x.Index), e.unsArg(x.Index))
		}
		return fmt.Sprintf("$elemPtr(%s, %s%s)", e.expr(x.X), e.expr(x.Index), e.unsArg(x.Index))
	}
	if id, ok := x.(*ir.Ident); ok {
		e.fail("the address of the name %s has no Dart form", id.Name)
		return "null"
	}
	e.fail("the address of %T has no Dart form", x)
	return "null"
}

// fieldIndex gives the position of a field in its struct. A pointer holds the
// index, thus 2 pointers to 1 field are equal.
func fieldIndex(t types.Type, field string) int {
	st, ok := typeset.Core(t).Underlying().(*types.Struct)
	if !ok {
		return -1
	}
	for i := 0; i < st.NumFields(); i++ {
		if st.Field(i).Name() == field {
			return i
		}
	}
	return -1
}

func (e *emitter) composite(x *ir.Composite) string {
	if text := e.deepSlice(x); text != "" {
		return text
	}
	if x.Results != nil {
		inner := x.Results
		x.Results = nil
		body := e.composite(x)
		x.Results = inner
		return fmt.Sprintf("((%s %s) => %s)(%s)",
			e.dartType(inner.GoType()), x.ResultsVar, body, e.expr(inner))
	}
	// A composite literal can name a type parameter. The constraint of such a
	// parameter is an interface, and the core type holds the shape.
	u := typeset.Core(x.Type)
	parts := make([]string, len(x.Elems))
	for i, el := range x.Elems {
		parts[i] = e.expr(el)
	}
	if x.Indices != nil {
		var allocation string
		switch t := u.(type) {
		case *types.Array:
			indices := make([]string, len(x.Indices))
			for i, index := range x.Indices {
				indices[i] = intConst(constant.MakeInt64(int64(index)), types.Typ[types.Int])
			}
			return fmt.Sprintf("$arrayLiteral<%s>(%s, <GoInt>[%s], <%s>[%s])",
				e.dartType(t.Elem()), e.makeArray(t), strings.Join(indices, ", "),
				e.dartType(t.Elem()), strings.Join(parts, ", "))
		case *types.Slice:
			allocation = fmt.Sprintf("$makeSliceN<%s>($gi(%d), %s)", e.dartType(t.Elem()), x.Length, e.alloc(t.Elem()))
		}
		var text strings.Builder
		text.WriteString("(" + allocation)
		for i, index := range x.Indices {
			fmt.Fprintf(&text, "..[%d] = %s", index, parts[i])
		}
		text.WriteString(")")
		return text.String()
	}
	switch u := u.(type) {
	case *types.Struct:
		// The class of an instance of a generic type writes each field with the
		// type that the declaration holds, thus a function value reads the
		// declaration and not the substituted type.
		decl := u
		if named, ok := types.Unalias(x.Type).(*types.Named); ok {
			if ref := e.structRef(named); ref.TypeArgs().Len() > 0 {
				if st, ok := ref.Origin().Underlying().(*types.Struct); ok {
					decl = st
				}
			}
		}
		for i, el := range x.Elems {
			if i < decl.NumFields() {
				parts[i] = e.funcAdapt(parts[i], el.GoType(), decl.Field(i).Type())
			}
		}
		if tp, ok := types.Unalias(x.Type).(*types.TypeParam); ok {
			return fmt.Sprintf("$structLiteral(%s.desc, <Object?>[%s])", e.dictOf(tp), strings.Join(parts, ", "))
		}
		// Go evaluates the value of a blank field and then discards it, thus
		// the field keeps its zero value.
		for i := range parts {
			if i < u.NumFields() && u.Field(i).Name() == "_" {
				parts[i] = fmt.Sprintf("((Object? $v) => %s)(%s)",
					e.zero(u.Field(i).Type()), parts[i])
			}
		}
		if named, ok := types.Unalias(x.Type).(*types.Named); ok && !isLocalType(e.structRef(named).Obj()) {
			parts = append(e.dictArgs(e.structRef(named).TypeArgs()), parts...)
		} else {
			parts = append(e.anonDicts(u), parts...)
		}
		return e.dartType(x.Type) + "(" + strings.Join(parts, ", ") + ")"
	case *types.Array:
		for len(parts) < int(u.Len()) {
			parts = append(parts, e.zero(u.Elem()))
		}
		return fmt.Sprintf("<%s>[%s]", e.dartType(u.Elem()), strings.Join(parts, ", "))
	case *types.Slice:
		return e.sliceLiteral(u.Elem(), parts)
	case *types.Map:
		var text strings.Builder
		fmt.Fprintf(&text, "(%s", e.mapNew(u))
		for i, key := range x.Keys {
			fmt.Fprintf(&text, "..set(%s, %s)", e.expr(key), parts[i])
		}
		text.WriteString(")")
		return text.String()
	}
	e.fail("a literal of type %s has no Dart form", x.Type)
	return "null"
}

// lowOrZero gives the first bound of a slice expression. Go reads 0 when the
// expression holds none.
func lowOrZero(low ir.Expr, e *emitter) string {
	if low == nil {
		return "$gi(0)"
	}
	return e.expr(low)
}
