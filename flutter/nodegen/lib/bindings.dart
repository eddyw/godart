import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import 'notices.dart';
import 'read.dart';
import 'write_go.dart';
import 'services.dart';

const generatedHeader = '// Code generated by nodegen. DO NOT EDIT.';

class Binding {
  Binding(this.pack, this.directory);
  final Pack pack;
  final String directory;
}

List<Binding> bindings(String root) {
  final file = File(p.join(root, 'glutter.bindings.json'));
  if (!file.existsSync()) return [];
  final data = jsonDecode(file.readAsStringSync());
  if (data is! Map || data['version'] != 1 || data['libraries'] is! List) {
    throw FormatException(
      'Expected version 1 and a libraries list in ${file.path}',
    );
  }
  final result = <Binding>[];
  final outputs = <String>{};
  final imports = <String>{};
  for (final entry in data['libraries'] as List) {
    if (entry is! Map ||
        entry['uri'] is! String ||
        entry['go_import'] is! String ||
        entry['directory'] is! String ||
        entry['symbols'] is! List ||
        (entry['functions'] != null && entry['functions'] is! List)) {
      throw const FormatException(
        'Each binding needs uri, go_import, directory, and symbols',
      );
    }
    final uri = entry['uri'] as String;
    final go = entry['go_import'] as String;
    final dir = entry['directory'] as String;
    final symbols = entry['symbols'] as List;
    final functions = (entry['functions'] as List?) ?? [];
    final name = go.split('/').last;
    if (!RegExp(r'^package:[a-z][a-z0-9_]*/[a-zA-Z0-9_./-]+\.dart$')
            .hasMatch(uri) ||
        !RegExp(r'^[a-zA-Z0-9_./-]+$').hasMatch(go) ||
        !RegExp(r'^[a-z][a-z0-9_]*$').hasMatch(name) ||
        {
          'break',
          'default',
          'func',
          'interface',
          'select',
          'case',
          'defer',
          'go',
          'map',
          'struct',
          'chan',
          'else',
          'goto',
          'package',
          'switch',
          'const',
          'fallthrough',
          'if',
          'range',
          'type',
          'continue',
          'for',
          'import',
          'return',
          'var',
        }.contains(name) ||
        p.isAbsolute(dir) ||
        !p.isWithin(p.absolute(root), p.absolute(root, dir)) ||
        (symbols.isEmpty && functions.isEmpty) ||
        functions.any(
          (s) =>
              s is! String || !RegExp(r'^[a-zA-Z][a-zA-Z0-9_]*$').hasMatch(s),
        ) ||
        symbols.any(
          (s) => s is! String || !RegExp(r'^[A-Z][a-zA-Z0-9]*$').hasMatch(s),
        )) {
      throw FormatException('Invalid binding entry: $entry');
    }
    if (!outputs.add(p.normalize(dir)) || !imports.add(go)) {
      throw const FormatException(
        'Binding directories and Go imports must be unique',
      );
    }
    result.add(
      Binding(
        Pack(
          uri,
          name,
          go,
          name,
          prefix: 'binding${result.length}',
          symbols: symbols.cast<String>().toSet(),
          functions: functions.cast<String>().toSet(),
        ),
        dir,
      ),
    );
  }
  return result;
}

Future<void> generateBindings(String root) async {
  final config = bindings(root);
  if (config.isEmpty)
    throw const FormatException('glutter.bindings.json has no libraries');
  final result = await read(
    root,
    libraries: config.map((b) => b.pack).toList(),
  );
  final outputs = <String, String>{};
  for (final binding in config) {
    final pack = binding.pack;
    final actual = result.widgets
        .where((w) => w.pack == pack)
        .map((w) => w.goName)
        .toSet();
    final names = {...actual, 'bindingCall'};
    for (final function in result.functions.where((f) => f.pack == pack)) {
      for (final name in [
        function.goName,
        if (function.stream) '${function.goName}Stream',
      ]) {
        if (!names.add(name)) {
          throw StateError('${pack.uri}: duplicate Go declaration $name');
        }
      }
    }
    final missing = pack.symbols!.difference(actual);
    if (missing.isNotEmpty) {
      final reasons = result.skipped
          .where((s) => missing.contains(s.name))
          .map((s) => '${s.name}: ${s.cause}');
      throw StateError(
        '${pack.uri}: unavailable constructors ${missing.join(", ")}\n${reasons.join("\n")}',
      );
    }
    final target = p.join(root, binding.directory, 'widgets_gen.go');
    final notices = sourceNotices(root, result.noticeSources[pack] ?? {});
    if (actual.isNotEmpty)
      outputs[target] = writeGo(result, pack, stampOf(root, pack), notices);
    if (pack.functions.isNotEmpty)
      outputs[p.join(root, binding.directory, 'services_gen.go')] =
          writeServicesGo(result, pack, notices);
  }
  final surfaceFile = File(p.join(root, 'glutter.bindings.surface.json'));
  if (FileSystemEntity.isLinkSync(surfaceFile.path)) {
    throw const FormatException(
      'The binding surface receipt must not be a symlink',
    );
  }
  final oldFiles = <String>{};
  if (surfaceFile.existsSync()) {
    final old = jsonDecode(surfaceFile.readAsStringSync());
    if (old is! Map ||
        old['version'] != 1 ||
        (old['files'] != null && old['files'] is! List)) {
      throw const FormatException('Invalid binding surface receipt');
    }
    for (final path in (old['files'] as List?) ?? []) {
      if (path is! String ||
          p.isAbsolute(path) ||
          !p.isWithin(p.absolute(root), p.absolute(root, path)) ||
          !{'widgets_gen.go', 'services_gen.go'}.contains(p.basename(path))) {
        throw const FormatException('Invalid generated binding path');
      }
      oldFiles.add(p.join(root, path));
    }
  }
  for (final path in {...outputs.keys, ...oldFiles}) {
    final file = File(path);
    var ancestor = file.parent;
    while (!ancestor.existsSync()) {
      ancestor = ancestor.parent;
    }
    final canonical = Directory(root).absolute.resolveSymbolicLinksSync();
    final parent = ancestor.resolveSymbolicLinksSync();
    if ((canonical != parent && !p.isWithin(canonical, parent)) ||
        FileSystemEntity.isLinkSync(path)) {
      throw FormatException('Binding output escapes the application: $path');
    }
    if (file.existsSync() &&
        !file.readAsStringSync().startsWith(generatedHeader)) {
      throw StateError('Refuse to replace a handwritten file: $path');
    }
  }
  final staged = Directory.systemTemp.createTempSync('glutter-bindings-');
  try {
    var index = 0;
    for (final entry in outputs.entries.toList()) {
      final file = File(p.join(staged.path, '${index++}.go'));
      file.writeAsStringSync(entry.value);
      final format = Process.runSync('gofmt', ['-w', file.path]);
      if (format.exitCode != 0) throw StateError('gofmt: ${format.stderr}');
      outputs[entry.key] = file.readAsStringSync();
    }
    for (final entry in outputs.entries) {
      final file = File(entry.key);
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(entry.value);
      stdout.writeln(file.path);
    }
    for (final path in oldFiles.difference(outputs.keys.toSet())) {
      final file = File(path);
      if (file.existsSync()) file.deleteSync();
    }
  } finally {
    staged.deleteSync(recursive: true);
  }
  final surface = {
    'version': 1,
    'files': [for (final path in outputs.keys) p.relative(path, from: root)],
    'functions': [
      for (final f in result.functions)
        {
          'name': f.key,
          'library': f.pack.uri,
          'result': f.dartResult,
          'future': f.future,
          'stream': f.stream,
        },
    ],
    'constructors': [
      for (final w in result.widgets)
        {
          'kind': w.kind,
          'library': w.pack.uri,
          'fields': [for (final p in w.params) p.goName],
        },
    ],
    'unsupported_members': [
      for (final m in result.unsupportedMembers)
        {
          'kind': m.kind,
          'member': m.member,
          'type': m.type,
          'reason': m.reason,
        },
    ],
  };
  File(p.join(root, 'glutter.bindings.surface.json')).writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(surface)}\n',
  );
  for (final member in result.unsupportedMembers) {
    stderr.writeln(
      'nodegen: ${member.kind}.${member.member}: ${member.type} (${member.reason})',
    );
  }
}
