/// writeDart gives the Dart source of the generated host. 1 case builds 1
/// Flutter widget from 1 node of the Go tree.
String writeDart(Reading r, {Set<String>? only, Set<String>? texts}) {
  final b = StringBuffer();
  b.writeln('// Code generated by nodegen. DO NOT EDIT.');
  b.writeln();
  b.writeln('// ignore_for_file: deprecated_member_use');
  b.writeln('// ignore_for_file: sort_child_properties_last');
  b.writeln('// ignore_for_file: unused_import');
  // A pack of Material or of Cupertino exports widgets.dart again, thus the
  // import of widgets.dart is unnecessary for such a host and necessary for a
  // host that holds no such case.
  b.writeln('// ignore_for_file: unnecessary_import');
  b.writeln();
  final kept =
      r.widgets.where((w) => only == null || only.contains(w.goName)).toList();
  final usedEnums = <String>{};
  for (final w in kept) {
    for (final p in w.params) {
      if (p.type.kind.startsWith('enum:')) {
        usedEnums.add(p.type.kind.substring(5));
      }
      // A callback of 1 enum names the table of that enum too. Read cb1Expr.
      if (p.type.kind.startsWith('cb1:enum:')) {
        usedEnums.add(p.type.kind.substring(9));
      }
    }
  }
  // The host imports the pack of each case that it holds, and no other 1. An
  // application that names no Material widget thus needs no material_ui. The
  // converter of an enum names its type, thus the library of each enum joins
  // the list.
  final imports = <String>{
    'package:flutter/widgets.dart',
    'package:goruntime/goruntime.dart',
    // goAppIcons names Icons, and the pack of Material exports it.
    'package:material_ui/material_ui.dart',
    for (final w in kept) w.pack.uri,
    for (final w in kept) ...w.needed,
    for (final name in usedEnums)
      if (r.visible[name] != null) r.visible[name]!,
  }.toList()
    ..sort();
  for (final uri in imports) {
    b.writeln("import '$uri';");
  }
  b.writeln();
  b.writeln("import 'package:goflutter/goflutter.dart';");
  b.writeln();
  b.writeln('/// goGenWidget builds the Flutter widget of 1 generated node. It');
  b.writeln('/// gives null when the node stands outside the generated set,');
  b.writeln('/// and goRender then reads its own cases.');
  b.writeln('Widget? goGenWidget(GoNode n, GoRuntime rt) {');
  b.writeln('  switch (n.kind) {');

  for (final w in kept) {
    b.writeln("    case '${w.kind}':");
    b.writeln('      return ${w.dartCall}(');
    for (var i = 0; i < w.params.length; i++) {
      final p = w.params[i];
      final arg = argExpr(w, p, i);
      b.writeln('        ${p.named ? "${p.dartName}: " : ""}$arg,');
    }
    b.writeln('      );');
  }

  b.writeln('  }');
  b.writeln('  return null;');
  b.writeln('}');
  b.writeln();

  // The Go source names an icon with a string. nodescan gives each string
  // constant of the application, and the set below holds each 1 that names an
  // icon of Material. A Go program thus needs no change of a Dart file.
  final names = <String>[
    for (final t in (texts ?? const <String>{}))
      if (r.icons.contains(t)) t,
  ]..sort();
  b.writeln('/// goAppIcons holds each icon of Material that the Go source of');
  b.writeln('/// this application names. goGenInstall puts it into goIcons.');
  b.writeln('const Map<String, IconData> goAppIcons = <String, IconData>{');
  for (final n in names) {
    b.writeln("  '$n': Icons.$n,");
  }
  b.writeln('};');
  b.writeln();
  b.writeln('/// goGenInstall installs the node set and the icons of this');
  b.writeln('/// application. Call it before runApp.');
  b.writeln('void goGenInstall() {');
  b.writeln('  goSetWidgets(goGenWidget);');
  b.writeln('  goIcons.addAll(goAppIcons);');
  b.writeln('}');

  writeEnums(b, r, usedEnums);
  return b.toString();
}

/// argExpr gives the Dart expression of 1 constructor argument. The position
/// of the field stands next to its name, and GoNode reads the position first.
/// The Go struct of the pack holds the fields in this order,
/// because writeGo writes the same list.
String argExpr(WidgetSpec w, Param p, int at) {
  final read = readExpr(p, at);
  if (!exprNullable(p)) return read;
  if (p.nullable) return read;
  if (p.required) {
    return "$read ?? (throw StateError('the field ${p.goName} of "
        "${w.goName} holds no value'))";
  }
  return '$read ?? ${p.defaultCode}';
}

/// exprNullable reports whether the read of 1 field can give null.
bool exprNullable(Param p) {
  if (p.optional) return true;
  switch (p.type.kind) {
    case 'str':
    case 'valueKey':
    case 'tag':
    case 'f64':
    case 'i64':
    case 'boolean':
    case 'color':
    case 'millis':
    case 'nodes':
    case 'strs':
    case 'counts':
    case 'sizes':
    case 'flags':
    case 'barItems':
    case 'railItems':
    case 'steps':
    case 'menuItems':
    case 'columns':
    case 'rows':
      return false;
  }
  return true;
}

