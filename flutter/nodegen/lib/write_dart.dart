import 'read.dart';

/// writeDart gives the Dart source of the generated host. 1 case builds 1
/// Flutter widget from 1 node of the Go tree.
String writeDart(Reading r, {Set<String>? only}) {
  final b = StringBuffer();
  b.writeln('// Code generated by nodegen. DO NOT EDIT.');
  b.writeln();
  b.writeln('// ignore_for_file: deprecated_member_use');
  b.writeln('// ignore_for_file: sort_child_properties_last');
  b.writeln('// ignore_for_file: unused_import');
  b.writeln();
  final imports = <String>{
    'package:flutter/cupertino.dart',
    'package:flutter/material.dart',
    'package:goruntime/goruntime.dart',
    ...r.needed,
  }.toList()
    ..sort();
  for (final uri in imports) {
    b.writeln("import '$uri';");
  }
  b.writeln();
  b.writeln("import 'package:goflutter/goflutter.dart';");
  b.writeln();
  b.writeln('/// goGenWidget builds the Flutter widget of 1 generated node. It');
  b.writeln('/// gives null when the node stands outside the generated set,');
  b.writeln('/// and goRender then reads its own cases.');
  b.writeln('Widget? goGenWidget(GoNode n, GoRuntime rt) {');
  b.writeln('  switch (n.kind) {');

  for (final w in r.widgets) {
    if (only != null && !only.contains(w.goName)) continue;
    b.writeln("    case 'gart.dev/ui.${w.goName}':");
    b.writeln('      return ${w.dartCall}(');
    for (final p in w.params) {
      final arg = argExpr(w, p);
      b.writeln('        ${p.named ? "${p.dartName}: " : ""}$arg,');
    }
    b.writeln('      );');
  }

  b.writeln('  }');
  b.writeln('  return null;');
  b.writeln('}');

  writeEnums(b, r);
  return b.toString();
}

/// argExpr gives the Dart expression of 1 constructor argument.
String argExpr(WidgetSpec w, Param p) {
  final read = readExpr(p);
  if (!exprNullable(p)) return read;
  if (p.nullable) return read;
  if (p.required) {
    return "$read ?? (throw StateError('the field ${p.goName} of "
        "${w.goName} holds no value'))";
  }
  return '$read ?? ${p.defaultCode}';
}

/// exprNullable reports whether the read of 1 field can give null.
bool exprNullable(Param p) {
  if (p.optional) return true;
  switch (p.type.kind) {
    case 'str':
    case 'f64':
    case 'i64':
    case 'boolean':
    case 'color':
    case 'millis':
    case 'nodes':
    case 'strs':
      return false;
  }
  return true;
}

/// readExpr gives the Dart expression that reads 1 field of the node.
String readExpr(Param p) {
  final f = "'${p.goName}'";
  final kind = p.type.kind;
  if (kind.startsWith('enum:')) {
    final name = kind.substring(5);
    return 'goEnum\$$name(${p.optional ? "n.textOpt($f)" : "n.text($f)"})';
  }
  if (kind.startsWith('widgetAs:')) {
    final name = kind.substring(9);
    return 'goCast<$name>(n.child($f), rt, ${"'"}${p.goName}${"'"})';
  }
  if (kind.startsWith('cb1:')) {
    return cb1Expr(kind.substring(4), f);
  }
  switch (kind) {
    case 'str':
      return p.optional ? 'n.textOpt($f)' : 'n.text($f)';
    case 'f64':
      return p.optional ? 'n.sizeOpt($f)' : 'n.size($f)';
    case 'i64':
      return p.optional ? 'n.countOpt($f)' : 'n.count($f)';
    case 'boolean':
      return p.optional ? 'n.flagOpt($f)' : 'n.flag($f)';
    case 'color':
      return p.optional ? 'goColorOpt(n.countOpt($f))' : 'Color(n.count($f))';
    case 'icon':
      return 'goIcon(${p.optional ? "n.textOpt($f)" : "n.text($f)"})';
    case 'millis':
      return p.optional
          ? 'goMillis(n.countOpt($f))'
          : 'Duration(milliseconds: n.count($f))';
    case 'alignment':
      return 'goAlignment(${p.optional ? "n.textOpt($f)" : "n.text($f)"})';
    case 'alignmentXY':
      return 'goAlignmentXY(${p.optional ? "n.textOpt($f)" : "n.text($f)"})';
    case 'curve':
      return 'goCurve(${p.optional ? "n.textOpt($f)" : "n.text($f)"})';
    case 'offset':
      return 'goOffset(n.nested($f))';
    case 'insets':
      return 'goInsets(n.nested($f))';
    case 'textStyle':
      return 'goTextStyle(n.nested($f))';
    case 'constraints':
      return 'goConstraints(n.nested($f))';
    case 'cursor':
      return 'goCursor(${p.optional ? "n.textOpt($f)" : "n.text($f)"})';
    case 'physics':
      return 'goPhysics(${p.optional ? "n.textOpt($f)" : "n.text($f)"})';
    case 'locale':
      return 'goLocale(${p.optional ? "n.textOpt($f)" : "n.text($f)"})';
    case 'borderSide':
      return 'goBorderSide(n.nested($f))';
    case 'radius':
      return 'goRadius(n.nested($f))';
    case 'shape':
      return 'goShape(n.nested($f))';
    case 'density':
      return 'goDensity(n.nested($f))';
    case 'iconStyle':
      return 'goIconStyle(n.nested($f))';
    case 'stateColor':
      return 'goStateColor(n.nested($f))';
    case 'node':
      return 'goChildOpt(n.child($f), rt)';
    case 'nodes':
      return 'goChildren(n.children($f), rt)';
    case 'strs':
      return 'n.texts($f)';
    case 'cb0':
      return 'goAction(n.action($f), rt)';
    case 'build0':
      return 'goBuild(n.build0($f), rt)';
    case 'build1':
      return 'goItem(n.item($f), rt)';
  }
  throw StateError('the kind $kind holds no read');
}

/// cb1Expr gives the read of a callback that takes 1 argument.
String cb1Expr(String arg, String f) {
  if (arg.startsWith('enum:')) {
    final name = arg.substring(5);
    return 'goOnEnum<$name>(n.onText($f), rt, goName\$$name)';
  }
  switch (arg) {
    case 'str':
      return 'goOnStr(n.onText($f), rt)';
    case 'f64':
      return 'goOnF64(n.onSize($f), rt)';
    case 'i64':
      return 'goOnI64(n.onCount($f), rt)';
    case 'boolean':
      return 'goOnBool(n.onFlag($f), rt)';
    case 'color':
      return 'goOnColor(n.onCount($f), rt)';
    case 'millis':
      return 'goOnDuration(n.onCount($f), rt)';
  }
  throw StateError('the callback argument $arg holds no read');
}

/// writeEnums gives 1 pair of converters for each Dart enum that a field
/// reads. The Go side carries the name of the value as a string.
void writeEnums(StringBuffer b, Reading r) {
  final names = r.enums.keys.toList()..sort();
  for (final name in names) {
    final values = r.enums[name]!;
    b.writeln();
    b.writeln('/// goEnum\$$name reads the Go name of 1 $name.');
    b.writeln('$name? goEnum\$$name(String? s) {');
    b.writeln('  switch (s) {');
    for (final v in values) {
      b.writeln("    case '$v':");
      b.writeln('      return $name.$v;');
    }
    b.writeln('  }');
    b.writeln('  return null;');
    b.writeln('}');
    b.writeln();
    b.writeln('/// goName\$$name writes the Go name of 1 $name.');
    b.writeln('String goName\$$name($name v) {');
    b.writeln('  switch (v) {');
    for (final v in values) {
      b.writeln('    case $name.$v:');
      b.writeln("      return '$v';");
    }
    b.writeln('  }');
    b.writeln('}');
  }
}
