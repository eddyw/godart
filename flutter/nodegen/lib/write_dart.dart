/// cb1Expr gives the read of a callback that takes 1 argument.
String cb1Expr(String arg, String f) {
  if (arg.startsWith('enum:')) {
    final name = arg.substring(5);
    return 'goOnEnum<$name>(n.onText($f), rt, goName\$$name)';
  }
  switch (arg) {
    case 'str':
      return 'goOnStr(n.onText($f), rt)';
    case 'f64':
      return 'goOnF64(n.onSize($f), rt)';
    case 'i64':
      return 'goOnI64(n.onCount($f), rt)';
    case 'boolean':
      return 'goOnBool(n.onFlag($f), rt)';
    case 'color':
      return 'goOnColor(n.onCount($f), rt)';
    case 'millis':
      return 'goOnDuration(n.onCount($f), rt)';
    case 'date':
      return 'goOnDate(n.onCount($f), rt)';
    case 'clock':
      return 'goOnClock(n.onCount($f), rt)';
  }
  throw StateError('the callback argument $arg holds no read');
}

/// writeEnums gives 1 pair of converters for each Dart enum that a field of
/// the cases below reads. The Go side carries the name of the value as a
/// string.
///
/// An enum of a pack that the host does not hold would name a type that the
/// host does not import, thus the writer reads the fields of the cases alone.
void writeEnums(StringBuffer b, Reading r, Set<String> used) {
  final names = r.enums.keys.where(used.contains).toList()..sort();
  for (final name in names) {
    final values = r.enums[name]!;
    b.writeln();
    b.writeln('/// goEnum\$$name reads the Go name of 1 $name.');
    b.writeln('$name? goEnum\$$name(String? s) {');
    b.writeln('  switch (s) {');
    for (final v in values) {
      b.writeln("    case '$v':");
      b.writeln('      return $name.$v;');
    }
    b.writeln('  }');
    b.writeln('  return null;');
    b.writeln('}');
    b.writeln();
    b.writeln('/// goName\$$name writes the Go name of 1 $name.');
    b.writeln('String goName\$$name($name v) {');
    b.writeln('  switch (v) {');
    for (final v in values) {
      b.writeln('    case $name.$v:');
      b.writeln("      return '$v';");
    }
    b.writeln('  }');
    b.writeln('}');
  }
}
