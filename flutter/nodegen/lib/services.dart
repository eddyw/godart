import 'notices.dart';
import 'read.dart';

String writeServicesGo(Reading r, Pack pack, String notices) {
  final b = StringBuffer('// Code generated by nodegen. DO NOT EDIT.\n');
  b.write(noticeHeader(notices));
  b.writeln('package ${pack.goPackage}');
  b.writeln('import ("encoding/json"; "gart.dev/ui")');
  b.writeln('''
func bindingCall(name string, args any, value any) error {
 data, err := json.Marshal(args)
 if err != nil { return err }
 text, err := ui.Call(name, string(data))
 if err != nil { return err }
 return json.Unmarshal([]byte(text), value)
}
''');
  for (final f in r.functions.where((f) => f.pack == pack)) {
    final params = [
      for (var i = 0; i < f.params.length; i++) 'arg$i ${f.params[i].goType}',
    ].join(', ');
    final args = [for (var i = 0; i < f.params.length; i++) 'arg$i'].join(', ');
    if (!f.stream) {
      b.writeln('''
// ${f.goName} calls ${pack.uri}.${f.name} and waits for its result.
// Call it from a goroutine. Dart exceptions return as Go errors.
func ${f.goName}($params) (${f.goResult}, error) {
 var value ${f.goResult}
 err := bindingCall("${f.key}", []any{$args}, &value)
 return value, err
}
''');
      continue;
    }
    b.writeln('''
// ${f.goName} opens a stream. Call Cancel when the consumer stops early.
// Next and Cancel must run from goroutines. Next permits 1 active call.
func ${f.goName}($params) (*${f.goName}Stream, error) {
 var id int
 if err := bindingCall("${f.key}", []any{$args}, &id); err != nil { return nil, err }
 return &${f.goName}Stream{id: id}, nil
}

type ${f.goName}Stream struct { id int }

// Next returns the next value. The boolean is false after the stream ends.
// Do not call Next after the stream ends or returns an error.
func (s *${f.goName}Stream) Next() (${f.goResult}, bool, error) {
 var item struct { Value ${f.goResult}; Done bool }
 err := bindingCall("${f.key}.next", s.id, &item)
 return item.Value, !item.Done && err == nil, err
}

func (s *${f.goName}Stream) Cancel() error {
 var canceled bool
 return bindingCall("${f.key}.cancel", s.id, &canceled)
}
''');
  }
  return b.toString();
}

void writeServicesDart(StringBuffer b, Reading r) {
  if (r.functions.isEmpty) return;
  b.writeln('void goGenServices() {');
  b.writeln('  goRegisterCalls({');
  for (final f in r.functions) {
    final args = <String>[];
    for (var i = 0; i < f.params.length; i++) {
      final p = f.params[i];
      final value = p.dartType == 'double'
          ? '(args[$i] as num).toDouble()'
          : 'args[$i] as ${p.dartType}';
      args.add('${p.named ? "${p.name}: " : ""}$value');
    }
    final call = '${f.pack.prefix}.${f.name}(${args.join(", ")})';
    b.writeln("    '${f.key}': (rt, payload) async {");
    if (f.params.isNotEmpty)
      b.writeln('      final args = jsonDecode(payload) as List<dynamic>;');
    b.writeln(
      '      return jsonEncode(${f.stream ? "rt.openStream($call)" : "${f.future ? "await " : ""}$call"});',
    );
    b.writeln('    },');
    if (f.stream) {
      b.writeln(
        "    '${f.key}.next': (rt, payload) async => jsonEncode(await rt.nextStream(jsonDecode(payload) as int)),",
      );
      b.writeln(
        "    '${f.key}.cancel': (rt, payload) async { await rt.cancelStream(jsonDecode(payload) as int); return 'true'; },",
      );
    }
  }
  b.writeln('  });');
  b.writeln('}');
}
