import 'read.dart';

/// writeGo gives the Go source of 1 pack of the generated node set.
///
/// The core pack stands in the package ui, and it declares the interface Node
/// itself. Each other pack stands in a package of its own, thus it imports the
/// core and it names the core types with the prefix ui.
String writeGo(Reading r, Pack pack) {
  final b = StringBuffer();
  b.writeln('// Code generated by nodegen. DO NOT EDIT.');
  b.writeln();
  b.writeln('package ${pack.goPackage}');
  b.writeln();
  if (!pack.isCore) {
    b.writeln('import "${corePack.goPath}"');
    b.writeln();
  }
  b.writeln('// This file holds 1 Go struct for each widget constructor of');
  b.writeln('// ${pack.uri} that the mapping of nodegen covers. A named');
  b.writeln('// constructor takes a struct of its own, and the host switches on');
  b.writeln('// the name of the type descriptor.');
  b.writeln('//');
  b.writeln('// An optional field is a pointer. A nil pointer means "the');
  b.writeln('// default of Flutter". Write ui.P to set one.');
  b.writeln('//');
  b.writeln('// Read flutter/nodegen/README.md to run the generator again.');

  final widgets = r.widgets.where((w) => w.pack == pack).toList();
  for (final w in widgets) {
    b.writeln();
    b.writeln('// ${w.goName} maps ${w.dartCall} of ${w.pack.uri}.');
    if (w.params.any((p) => p.type.kind.startsWith('enum:'))) {
      for (final p in w.params.where((p) => p.type.kind.startsWith('enum:'))) {
        final name = p.type.kind.substring(5);
        final values = r.enums[name] ?? const <String>[];
        b.writeln('//');
        b.writeln('// ${p.goName} takes ${quoteList(values)}.');
      }
    }
    b.writeln('type ${w.goName} struct {');
    for (final p in w.params) {
      b.writeln('\t${goDecl(p, pack)}');
    }
    b.writeln('}');
  }

  b.writeln();
  final mark = pack.isCore ? 'Mark' : 'ui.Mark';
  for (final w in widgets) {
    b.writeln('func (${w.goName}) IsNode() $mark { return $mark{} }');
  }
  return b.toString();
}

/// goDecl gives the declaration of 1 field. A type of the core carries the
/// prefix ui outside the core, and a builtin type carries none.
String goDecl(Param p, Pack pack) {
  final star = p.optional ? '*' : '';
  return '${p.goName} $star${qualify(p.type.goType, pack)}';
}

/// qualify names a type of the core package from inside a pack.
///
/// Each type of the core starts with an upper case letter, and each builtin
/// type of Go starts with a lower case 1.
String qualify(String goType, Pack pack) {
  if (pack.isCore) return goType;
  final head = goType.startsWith('[]') ? goType.substring(2) : goType;
  if (head.isEmpty || head[0].toLowerCase() == head[0]) return goType;
  return goType.startsWith('[]')
      ? '[]${corePack.goPackage}.$head'
      : '${corePack.goPackage}.$goType';
}

String quoteList(List<String> values) {
  if (values.isEmpty) return 'no value';
  final quoted = values.map((v) => '"$v"').toList();
  if (quoted.length == 1) return quoted.first;
  return '${quoted.sublist(0, quoted.length - 1).join(", ")}, '
      'or ${quoted.last}';
}
